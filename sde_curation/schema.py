"""PostgreSQL schema as numbered migrations. `MIGRATIONS[n]` is applied once, in order, under a
`schema_version` table; a running engine only ever applies the versions it has not seen. Version 1
is the whole schema in its current shape (there is no ALTER history to replay: databases created
by the SQLite era are brought over by `sde_curation.import_sqlite`)."""

from __future__ import annotations

# One key for every engine process that runs migrations: two tasks booting at once serialise here.
MIGRATION_LOCK_KEY = 0x5DE_C0DE

