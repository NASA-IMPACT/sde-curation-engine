# The curated set carries the page text it was approved with, so an export never depends on the
# dump still holding that crawl. Existing rows take the current dump text: before this column the
# export always shipped the dump text, so that is exactly what the index holds for them.
V2 = """
ALTER TABLE curated_urls ADD COLUMN full_text text;
UPDATE curated_urls c SET full_text = d.full_text
  FROM dump_urls d WHERE d.collection_id = c.collection_id AND d.url = c.url;
"""

# V3: URL identity and crawl failures in the diff — a delta may rename a curated row (same page,
# new spelling), tombstones carry the crawler's reason, curated rows the crawl could not fetch
# are kept and flagged, and the dump remembers what the crawler failed on and whether it was capped.
V3 = """
CREATE TABLE dump_failures (
  collection_id text NOT NULL REFERENCES collections(collection_id) ON DELETE CASCADE,
  url text NOT NULL,
  reason text NOT NULL,
  status integer,
  detail text,
  PRIMARY KEY (collection_id, url)
);
ALTER TABLE delta_urls ADD COLUMN renamed_from text;
ALTER TABLE delta_urls ADD COLUMN crawl_failure text;
ALTER TABLE curated_urls ADD COLUMN crawl_failure text;
ALTER TABLE collections ADD COLUMN last_crawl_capped boolean NOT NULL DEFAULT false;
"""

# V4: a Suggest metadata call that failed for a URL (after the in-job retry) is recorded on the row,
# so the failure is visible per URL and "Suggest missing" retries it; both clear on the next answer.
V4 = """
ALTER TABLE delta_urls ADD COLUMN ai_error text;
ALTER TABLE delta_urls ADD COLUMN ai_failures integer NOT NULL DEFAULT 0;
"""

# V5: "Regenerate duplicate titles" replaces a page's AI title with one that sets it apart from the pages it shared
# its title and document type with; the title it shared is kept, so the SME sees what it was.
V5 = """
ALTER TABLE delta_urls ADD COLUMN title_ai_before text;
"""

# V6: the collection_key / collection_name a collection is indexed under. Normally derived from the
# name (the COSMOS rule) and pinned by the first index run; set by hand when the folder differs.
V6 = """
ALTER TABLE collections ADD COLUMN index_key text;
ALTER TABLE collections ADD COLUMN index_name text;
"""

# V7: `curated_count` becomes the number of curated URLs that reach the index (the included ones),
# because that is the number the curator is told; `curated_rows` keeps the size of the whole set
# (included + excluded — the Curated URLs list shows both) for the checks that ask "has anything
# been promoted". `curated_changed_at` is when the curated set last changed: an index run started
# before it is behind the curated set, which is what the "needs re-indexing" chip reads.
V7 = """
ALTER TABLE collections ADD COLUMN curated_rows integer NOT NULL DEFAULT 0;
ALTER TABLE collections ADD COLUMN curated_changed_at timestamptz;
UPDATE collections c SET
  curated_rows = (SELECT COUNT(*) FROM curated_urls u WHERE u.collection_id = c.collection_id),
  curated_count = (SELECT COUNT(*) FROM curated_urls u WHERE u.collection_id = c.collection_id AND NOT u.excluded);
"""

# V8: the row was classified while the collection had a real division, so the model was never asked
# for one (`suggest_metadata_one` drops the field from the schema). Together with a division back at
# the General placeholder it is the one state that means "this row still owes a division and nobody
# has been asked": it can only arise once the curator puts the collection back to General, and it is
# what lets Suggest metadata ask for the divisions alone instead of re-classifying every field of
# every page. It does not collide with a suggestion the SME dismissed — that row was asked, and was
# never skipped.
V8 = """
ALTER TABLE delta_urls ADD COLUMN division_skipped boolean NOT NULL DEFAULT false;
"""

# V9: the page text is stored once, not twice. `dump_urls.full_text` and `curated_urls.full_text`
# held the same bytes for every URL whose curated row was approved with the text the dump still
# has — which is nearly all of them — so a collection cost two copies of its crawl in the database
# and the RDS volume grew at twice the rate the crawls did. Both tables already carry the
# `content_hash` that fingerprints exactly those bytes (`engine.text.content_hash`; V2 and
# `engine.diff.promote` keep it true of the curated row too), so it becomes the key of a
# content-addressed `page_text` table both sides point at. Nothing in the app's behaviour changes:
# a curated row still serves the text it was approved with, because a re-crawl that changes a page
# gives it a new hash and the old blob is kept until no row references it (`Database.gc_page_text`).
#
# Two pages whose text differs only in whitespace hash the same (the hash is of the normalised
# text) and so now share one blob: the raw spacing kept is whichever was ingested first. That is
# invisible to the index, which is the only reader.
#
# Storage note: DROP COLUMN does not free the TOAST the column pointed at, so the text is NULLed
# first — that makes the old TOAST rows dead and autovacuum returns them to the table's free space,
# which is what stops the volume growing. To hand the space back to the OS as well, run
# `make db-compact` (VACUUM FULL) in a maintenance window. Both the extraction and the NULLing
# happen in this one transaction, so the migration itself needs headroom for one more copy of the
# text while it runs: raise the volume ceiling before deploying it.
#
# Rows old enough to predate hashing have text but no hash, and the hash is now the only way to
# hold text — so they are given one here, computed the way `engine.text.content_hash` computes it
# (collapse whitespace runs, strip, sha256 of the UTF-8). PostgreSQL's `\s` and Python's
# `str.split()` disagree about a few exotic Unicode spaces, so such a row could come out with a
# hash Python would not have produced. That is harmless: the same expression keys the blob and
# stamps the row, so they always agree with each other, and the next crawl replaces the hash with
# a Python-computed one (at worst flagging the page as content-changed once, which for a row
# nobody ever hashed is the honest answer).
V9 = r"""
UPDATE dump_urls SET content_hash =
    encode(sha256(convert_to(btrim(regexp_replace(full_text, '\s+', ' ', 'g')), 'UTF8')), 'hex')
  WHERE content_hash IS NULL AND btrim(regexp_replace(full_text, '\s+', ' ', 'g')) <> '';
UPDATE curated_urls SET content_hash =
    encode(sha256(convert_to(btrim(regexp_replace(full_text, '\s+', ' ', 'g')), 'UTF8')), 'hex')
  WHERE content_hash IS NULL AND btrim(regexp_replace(full_text, '\s+', ' ', 'g')) <> '';
CREATE TABLE page_text (
  collection_id text NOT NULL REFERENCES collections(collection_id) ON DELETE CASCADE,
  content_hash text NOT NULL,
  full_text text NOT NULL,
  PRIMARY KEY (collection_id, content_hash)
);
INSERT INTO page_text (collection_id, content_hash, full_text)
  SELECT collection_id, content_hash, full_text FROM dump_urls
   WHERE content_hash IS NOT NULL AND full_text IS NOT NULL
  ON CONFLICT (collection_id, content_hash) DO NOTHING;
INSERT INTO page_text (collection_id, content_hash, full_text)
  SELECT collection_id, content_hash, full_text FROM curated_urls
   WHERE content_hash IS NOT NULL AND full_text IS NOT NULL
  ON CONFLICT (collection_id, content_hash) DO NOTHING;
CREATE INDEX dump_urls_hash ON dump_urls (collection_id, content_hash);
CREATE INDEX curated_urls_hash ON curated_urls (collection_id, content_hash);
UPDATE dump_urls SET full_text = NULL WHERE full_text IS NOT NULL;
UPDATE curated_urls SET full_text = NULL WHERE full_text IS NOT NULL;
ALTER TABLE dump_urls DROP COLUMN full_text;
ALTER TABLE curated_urls DROP COLUMN full_text;
"""

# Who is curating a collection: whoever last pressed Start curating / Check for changes /
# Re-curate everything (the recompute endpoint), so the dashboard's Curator filter follows the work
# rather than whoever added the collection. Existing rows take the last recompute in the audit log;
# a collection nobody has curated stays NULL and the dashboard falls back to `created_by`.
V10 = """
ALTER TABLE collections ADD COLUMN curated_by text;
UPDATE collections c SET curated_by = a.actor FROM (
  SELECT DISTINCT ON (collection_id) collection_id, actor FROM audit_log
   WHERE action IN ('recompute', 'recompute.all') AND collection_id IS NOT NULL
   ORDER BY collection_id, id DESC
) a WHERE a.collection_id = c.collection_id;
"""

MIGRATIONS: list[tuple[int, str]] = [(1, V1), (2, V2), (3, V3), (4, V4), (5, V5), (6, V6), (7, V7), (8, V8),
                                     (9, V9), (10, V10)]

# Every application table, parents before children (the order the importer copies them in, and
# the order TRUNCATE ... CASCADE does not care about).
TABLES = (
    "collections", "status_history", "page_text", "dump_urls", "dump_failures", "delta_urls", "curated_urls",
    "patterns", "pattern_effects", "pattern_suggestions", "index_runs", "job_runs", "users", "audit_log",
)

_VERSION_TABLE = (
    "CREATE TABLE IF NOT EXISTS schema_version ("
    "version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())"
)


def pending(current: int) -> list[tuple[int, str]]:
    return [(v, sql) for v, sql in MIGRATIONS if v > current]


def migrate_sync(conn) -> int:
    """Apply missing migrations on a sync psycopg connection (importer, tests). Returns the
    resulting schema version. One transaction, serialised by an advisory lock."""
    with conn.transaction():
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (MIGRATION_LOCK_KEY,))
        conn.execute(_VERSION_TABLE)
        current = conn.execute("SELECT COALESCE(MAX(version), 0) FROM schema_version").fetchone()[0]
        for version, sql in pending(current):
            conn.execute(sql)
            conn.execute("INSERT INTO schema_version (version) VALUES (%s)", (version,))
            current = version
    return current


async def migrate_async(conn) -> int:
    """Same as `migrate_sync` for an async connection (the engine at start-up)."""
    async with conn.transaction():
        await conn.execute("SELECT pg_advisory_xact_lock(%s)", (MIGRATION_LOCK_KEY,))
        await conn.execute(_VERSION_TABLE)
        cur = await conn.execute("SELECT COALESCE(MAX(version), 0) AS v FROM schema_version")
        row = await cur.fetchone()
        current = row["v"] if isinstance(row, dict) else row[0]
        for version, sql in pending(current):
            await conn.execute(sql)
            await conn.execute("INSERT INTO schema_version (version) VALUES (%s)", (version,))
            current = version
    return current
